#!/usr/bin/env node
/**
 * Bakes each bright star's proper motion (its own drift across the sky) for the Aether sky over
 * millennia (Paulo, Nov 10). Source: Hipparcos, the new reduction (van Leeuwen 2007, A&A 474),
 * via ESA's Gaia archive TAP service. Asked once at build time; the app ships the numbers.
 *
 * Matching: the brightest Hipparcos star within 0.4° of each BRIGHT_STARS position, and only if
 * its magnitude is within 1.5 of ours (otherwise the star is left out rather than guessed).
 * Output: lib/starMotion.ts. Run: node scripts/build-star-motion.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = await readFile(path.join(here, "..", "lib", "brightStars.ts"), "utf8");
const stars = [...src.matchAll(/\{\s*id:\s*"([^"]+)"[^}]*?\bra:\s*(-?[\d.]+),\s*dec:\s*(-?[\d.]+),\s*mag:\s*(-?[\d.]+)/g)].map(m => ({
  id: m[1],
  ra: Number(m[2]),
  dec: Number(m[3]),
  mag: Number(m[4]),
}));

const TAP = "https://gea.esac.esa.int/tap-server/tap/sync";
async function lookup(s) {
  const q = `SELECT TOP 1 hip, pm_ra, pm_de, hp_mag FROM public.hipparcos_newreduction WHERE 1=CONTAINS(POINT('ICRS',ra,dec),CIRCLE('ICRS',${(s.ra * 15).toFixed(5)},${s.dec.toFixed(5)},0.4)) ORDER BY hp_mag`;
  const body = new URLSearchParams({ REQUEST: "doQuery", LANG: "ADQL", FORMAT: "csv", QUERY: q });
  for (let k = 0; k < 3; k++) {
    try {
      const res = await fetch(TAP, { method: "POST", body, headers: { "user-agent": "pneuma-build/1.0" } });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const [, row] = (await res.text()).trim().split(/\r?\n/);
      if (!row) return null;
      const [hip, pmRa, pmDe, hp] = row.split(",").map(Number);
      return { hip, pmRa, pmDe, hp };
    } catch (e) {
      if (k === 2) throw e;
      await new Promise(r => setTimeout(r, 1500 * (k + 1)));
    }
  }
  return null;
}

const out = [];
const skipped = [];
for (const s of stars) {
  const r = await lookup(s);
  if (!r || !Number.isFinite(r.pmRa) || !Number.isFinite(r.pmDe) || Math.abs(r.hp - s.mag) > 1.5) {
    skipped.push(`${s.id}${r ? ` (nearest HIP ${r.hip}, Hp ${r.hp})` : ""}`);
    continue;
  }
  out.push(`  ${JSON.stringify(s.id)}: [${r.hip}, ${r.pmRa.toFixed(2)}, ${r.pmDe.toFixed(2)}],`);
  process.stdout.write(".");
}
console.log(`\n${out.length} stars matched; skipped: ${skipped.join(", ") || "none"}`);

const ts = `/**
 * Proper motions of the bright stars: how far each drifts across the sky on its own, in
 * milliarcseconds a year (RA term already times cos Dec, as Hipparcos gives it).
 * Hipparcos new reduction (van Leeuwen 2007, A&A 474), via ESA's Gaia archive.
 * Generated by scripts/build-star-motion.mjs on ${new Date().toISOString().slice(0, 10)}; do not hand-edit.
 * Stars left out (no confident match): ${skipped.join(", ") || "none"}.
 */
export const STAR_MOTION: Readonly<Record<string, readonly [hip: number, pmRaMasYr: number, pmDecMasYr: number]>> = {
${out.join("\n")}
};
`;
await writeFile(path.join(here, "..", "lib", "starMotion.ts"), ts);
console.log("wrote lib/starMotion.ts");
